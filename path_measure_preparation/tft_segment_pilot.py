"""Snapshot interventions for low-health and level-vs-refresh candidates.

Source states are generated by the original diffusion policy. For each state,
two legal actions are forced once and then ALL players use the econ script.
Paired continuations share RNG seeds, but differing actions can desynchronize
later randomness. Results estimate a one-action effect under that continuation,
not a causal credit assignment for full model trajectories.
"""
import copy
import contextlib
import hashlib
import io
import json
import multiprocessing as mp
import random
import time
from concurrent.futures import ProcessPoolExecutor,as_completed
import numpy as np
import torch
from Simulator import TFTConfig,parallel_env
from Simulator.rng import EnvRNG
from agent_measure.hierarchical_policy import HierarchicalDenoiser
from tft_intense_game import BASE
from tft_opponents import econ_policy,rank_events
from tft_pilot_train import features

OUT=BASE/'tft_segment_pilot_20261124'
MODELS={'original':BASE/'tft_econ_imitation_20261124/hier_diffusion.pt',
        'dagger':BASE/'tft_dagger_20261124/dagger.pt',
        'fresh_teacher':BASE/'tft_dagger_20261124/fresh_teacher.pt'}
REPLICATES=4

def load_models():
    result={}
    for name,path in MODELS.items():
        ck=torch.load(path,map_location='cpu',weights_only=False)
        model=HierarchicalDenoiser(len(ck['mean']));model.load_state_dict(ck['model']);model.eval()
        result[name]=(model,ck['mean'],ck['std'])
    return result

def sample(model_bundle,observation,seed=None):
    model,mean,std=model_bundle
    if seed is not None:torch.manual_seed(seed)
    mask=np.asarray(observation['action_mask'],dtype=bool).reshape(-1)
    x=np.clip((features(observation)-mean)/std,-10,10).astype(np.float32)
    with torch.no_grad():
        action=int(model.sample(torch.from_numpy(x)[None,:],torch.from_numpy(mask)[None,:]).item())
    if not mask[action]:raise ValueError('illegal sampled proposal')
    return action

def available(mask,row):
    return np.flatnonzero(mask & (np.arange(mask.size)//38==row))

def choice_for(case,mask,player):
    refresh=available(mask,54);level=available(mask,53);passes=available(mask,52)
    if case=='low_health' and player.health<=40 and len(refresh) and len(passes):
        return {'refresh':int(refresh[0]),'pass':int(passes[0])}
    if case=='level_refresh' and player.round>=6 and len(refresh) and len(level):
        return {'level':int(level[0]),'refresh':int(refresh[0])}
    return None

def unit_info(unit):
    if unit is None:return None
    return {'name':str(unit.name),'stars':int(unit.stars),'items':list(unit.items)}

def branch(bundle,target,forced_action,continuation_seed):
    env,obs,infos,rngs,alive,ranks=copy.deepcopy(bundle)
    root=env.aec_env.unwrapped
    root.rng=EnvRNG.from_episode_seed(continuation_seed);root.combat_ctx.rng=root.rng
    rngs={a:np.random.default_rng(continuation_seed*100+i+8192) for i,a in enumerate(env.possible_agents)}
    random.seed(continuation_seed);np.random.seed(continuation_seed)
    initial_player=infos[target]['player'];initial_health=float(initial_player.health);initial_round=int(initial_player.round)
    next_round_health=None;warnings=[];digest=hashlib.sha256();reason='step_limit'
    try:
        for step in range(900):
            if not env.agents:reason='natural_end';break
            actions={}
            for a in env.agents:
                if a not in obs or obs[a] is None:continue
                mask=np.asarray(obs[a]['action_mask'],dtype=bool).reshape(-1)
                action=forced_action if step==0 and a==target else econ_policy(mask,infos.get(a,{}),rngs[a],obs[a])
                if not mask[action]:raise ValueError('branch action invalid')
                actions[a]=action;digest.update(a.encode());digest.update(int(action).to_bytes(4,'little'))
                digest.update(features(obs[a]).tobytes())
            if not actions:reason='no_actions';break
            with contextlib.redirect_stdout(io.StringIO()) as buf:
                obs,rewards,terms,truncs,infos=env.step(actions)
            warnings += [l[:180] for l in buf.getvalue().splitlines() if any(w in l.lower() for w in ('failed','could not','should never'))]
            player=infos.get(target,{}).get('player')
            if player is not None and next_round_health is None and int(player.round)>initial_round:
                next_round_health=float(player.health)
            ended=[a for a,done in terms.items() if done and a in alive]
            if ended:
                result=rank_events(ended,alive,infos,rewards)
                if result is None:reason='ambiguous_terminal';break
                ranks.update(result);alive.difference_update(ended)
            for a in sorted(rewards):digest.update(np.float64(rewards[a]).tobytes())
        if reason=='natural_end' and (alive or set(ranks.values())!=set(range(1,9))):reason='invalid_ranking'
        return {'reason':reason,'rank':ranks.get(target),'steps':step+1,'initial_health':initial_health,
                'next_round_health':next_round_health,'warnings':len(warnings),'warning_examples':warnings[:3],
                'digest':digest.hexdigest()}
    finally:env.close()

def seek(task):
    seed=task['seed'];case=task['case'];replicates=task.get('replicates',REPLICATES)
    random.seed(seed);np.random.seed(seed);torch.manual_seed(seed+400000);torch.set_num_threads(1)
    models=load_models();env=parallel_env(TFTConfig(num_players=8));obs,infos=env.reset(seed=seed)
    target=f'player_{seed%8}';rngs={a:np.random.default_rng(seed*100+i+8192) for i,a in enumerate(env.possible_agents)}
    alive=set(env.agents);ranks={};warnings=[];start=time.monotonic()
    try:
        for step in range(900):
            if not env.agents:break
            if time.monotonic()-start>180:raise RuntimeError('source time limit')
            if target in env.agents and target in obs and infos.get(target,{}).get('player') is not None:
                player=infos[target]['player'];mask=np.asarray(obs[target]['action_mask'],dtype=bool).reshape(-1)
                choices=choice_for(case,mask,player)
                if choices:
                    bundle=(env,obs,infos,rngs,alive,ranks)
                    state_vector=features(obs[target])
                    fingerprint=hashlib.sha256(state_vector.tobytes()+mask.astype(np.uint8).tobytes()).hexdigest()
                    if task.get('expected_fingerprint') and fingerprint!=task['expected_fingerprint']:
                        return {'seed':seed,'case':case,'reason':'snapshot_mismatch','fingerprint':fingerprint}
                    # Same-state candidates only, prior to executing any actions.
                    proposals={name:sample(model,obs[target],seed*10+i+800000) for i,(name,model) in enumerate(models.items())}
                    proposals['econ']=int(econ_policy(mask,infos[target],np.random.default_rng(seed+22),obs[target]))
                    state={'seed':seed,'case':case,'target':target,'step':step,'round':int(player.round),
                           'health':float(player.health),'gold':float(player.gold),'level':int(player.level),
                           'board':[[unit_info(unit) for unit in column] for column in player.board],
                           'bench':[unit_info(unit) for unit in player.bench],
                           'shop':[str(x) if x is not None else None for x in player.shop],
                           'observation':state_vector.tolist(),'fingerprint':fingerprint,
                           'legal_actions':np.flatnonzero(mask).tolist(),
                           'choices':choices,'proposals':proposals,'source_warnings':len(warnings),
                           'source_warning_examples':warnings[:3]}
                    outcome={name:[] for name in choices}
                    for i in range(task.get('replicate_start',0),task.get('replicate_start',0)+replicates):
                        continuation_seed=(seed*37+i+7000000)%(2**31-1)
                        for name,action in choices.items():
                            value=branch(bundle,target,action,continuation_seed)
                            value['continuation_seed']=continuation_seed;outcome[name].append(value)
                    state['outcomes']=outcome
                    if task.get('verify_replay'):
                        first_name=next(iter(choices));v=outcome[first_name][0]
                        repeat=branch(bundle,target,choices[first_name],v['continuation_seed'])
                        state['repeat_same_action_matches']=(repeat['digest']==v['digest'] and repeat['rank']==v['rank']
                                                               and repeat['reason']==v['reason'])
                    state['reason']='completed';return state
            actions={}
            for a in env.agents:
                mask=np.asarray(obs[a]['action_mask'],dtype=bool).reshape(-1)
                actions[a]=sample(models['original'],obs[a]) if a==target else econ_policy(mask,infos.get(a,{}),rngs[a],obs[a])
            with contextlib.redirect_stdout(io.StringIO()) as buf:obs,rewards,terms,truncs,infos=env.step(actions)
            warnings += [l[:180] for l in buf.getvalue().splitlines() if any(w in l.lower() for w in ('failed','could not','should never'))]
            ended=[a for a,done in terms.items() if done and a in alive]
            if ended:
                result=rank_events(ended,alive,infos,rewards)
                if result is None:raise RuntimeError('source ambiguous terminal')
                ranks.update(result);alive.difference_update(ended)
        return {'seed':seed,'case':case,'reason':'no_matching_state','source_warnings':len(warnings)}
    finally:env.close()

def save(result):
    tmp=OUT/'metrics.tmp';tmp.write_text(json.dumps(result,indent=2,allow_nan=False),encoding='utf8');tmp.replace(OUT/'metrics.json')

def main():
    OUT.mkdir(parents=True,exist_ok=True);started=time.monotonic()
    result={'status':'running','tasks':[],'notes':['small exploratory pilot; no training or policy selection',
      'source states from original diffusion; no representative coverage guarantee',
      'forced first action then economy script controls every player',
      'continuations use re-seeded simulator and policy RNG; same seed can diverge after actions',
      'round change health is a proxy, not guaranteed immediate battle outcome',
      'no claim of general causal benefit or fixed point','snapshot reproducibility checked only on limited states']};save(result)
    jobs=[{'seed':s,'case':c} for c in ('low_health','level_refresh') for s in range(62101,62109)]
    with ProcessPoolExecutor(max_workers=4,mp_context=mp.get_context('spawn')) as pool:
        futures={pool.submit(seek,j):j for j in jobs}
        for future in as_completed(futures):
            try:out=future.result()
            except Exception as exc:out={**futures[future],'reason':'worker_error','error':repr(exc)}
            result['tasks'].append(out);save(result)
            print('case',{'seed':out.get('seed'),'case':out.get('case'),'reason':out.get('reason'),
                          'health':out.get('health'),'round':out.get('round'),'error':out.get('error')},flush=True)
    result['status']='completed';result['elapsed_seconds']=round(time.monotonic()-started,2);save(result)
    print('COMPLETED',flush=True)

if __name__=='__main__':main()
